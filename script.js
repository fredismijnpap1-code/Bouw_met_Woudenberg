// ── BUILD LIGHTBOX HTML ───────────────────────────────────────────────────────
function buildLightbox(p) {
  const imgs = p.images;

  // Build image grid depending on count
  let gridHtml = '';
  if (imgs.length === 1) {
    gridHtml = `<div class="lb-grid-full"><div class="lb-img wide"><img src="${imgs[0].src}" alt="${imgs[0].caption}"></div></div>`;
  } else if (imgs.length === 2) {
    gridHtml = `<div class="lb-grid-sub2">${imgs.map(i=>`<div class="lb-img wide"><img src="${i.src}" alt="${i.caption}"></div>`).join('')}</div>`;
  } else if (imgs.length === 3) {
    gridHtml = `
      <div class="lb-grid-main">
        <div class="lb-img wide"><img src="${imgs[0].src}" alt="${imgs[0].caption}"></div>
        <div class="lb-img tall"><img src="${imgs[1].src}" alt="${imgs[1].caption}"></div>
      </div>
      <div class="lb-grid-full"><div class="lb-img wide"><img src="${imgs[2].src}" alt="${imgs[2].caption}"></div></div>`;
  } else {
    // 4+ images: first big, rest sub-grid
    gridHtml = `
      <div class="lb-grid-main">
        <div class="lb-img wide"><img src="${imgs[0].src}" alt="${imgs[0].caption}"></div>
        <div class="lb-img tall"><img src="${imgs[1].src}" alt="${imgs[1].caption}"></div>
      </div>
      <div class="lb-grid-sub">${imgs.slice(2).map(i=>`<div class="lb-img auto"><img src="${i.src}" alt="${i.caption}"></div>`).join('')}</div>`;
  }

  const metaHtml = p.meta.map(m => `<div class="lb-meta-item"><dt>${m.label}</dt><dd>${m.value}</dd></div>`).join('');
  const descHtml = p.desc.map(d => `<p>${d}</p>`).join('');
  const featHtml = p.features.map(f => `<li><span class="lb-feat-dot">▸</span>${f}</li>`).join('');

  return `
    <div class="lb-back" onclick="closeLightbox()">← Terug naar projecten</div>
    <div class="lb-header">
      <span class="lb-tag">${p.tag}</span>
      <h2 class="lb-title">${p.title}</h2>
      <p class="lb-subtitle">${p.subtitle}</p>
    </div>
    <div class="lb-meta">${metaHtml}</div>
    ${gridHtml}
    <div class="lb-description">
      <div class="lb-desc-text">
        <h3>Over dit project</h3>
        ${descHtml}
      </div>
      <div>
        <h3 style="font-family:var(--font);font-size:1.1rem;font-weight:700;color:var(--cream);margin-bottom:0.5rem;">Wat wij verzorgden</h3>
        <ul class="lb-features">${featHtml}</ul>
      </div>
    </div>
    <div class="lb-cta">
      <div>
        <p>Vergelijkbaar project laten realiseren?</p>
        <span>Neem contact op voor een vrijblijvend gesprek en offerte op maat.</span>
      </div>
      <a href="#contact" class="btn-fill" onclick="closeLightbox()" style="white-space:nowrap;">Offerte aanvragen →</a>
    </div>`;
}

