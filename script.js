// ── LIGHTBOX OPEN / CLOSE ────────────────────────────────────────────────────
function openLightbox(key) {
  const p = PROJECTS[key];
  if (!p) return;
  document.getElementById('lb-content').innerHTML = buildLightbox(p);
  document.getElementById('lb-overlay').classList.add('open');
  document.body.style.overflow = 'hidden';
  // bind zoom on images inside lightbox
  document.querySelectorAll('.lb-img img').forEach(img => {
    img.addEventListener('click', e => { e.stopPropagation(); openZoom(img.src); });
  });
}

function closeLightbox() {
  document.getElementById('lb-overlay').classList.remove('open');
  document.getElementById('lb-overlay').scrollTop = 0;
  document.body.style.overflow = '';
}

